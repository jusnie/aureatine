const streamHelpers=readFileSync(new URL('shared/chatStream.js',root),'utf8').replace(/^export /gm,'')
const timing=readFileSync(new URL('shared/chatTiming.js',root),'utf8').replace(/^export /gm,'')
const core=readFileSync(new URL('api/chat.js',root),'utf8')
 .replace(/^import .*\n/gm,'')
 .replace('export default async function handler','async function handler')
 .replaceAll('process.env.CHAT_ENABLED',"Deno.env.get('CHAT_ENABLED')")
 .replaceAll('process.env.NVIDIA_API_KEY',"Deno.env.get('NVIDIA_API_KEY')")
 .replaceAll('process.env.NVIDIA_MODEL',"Deno.env.get('NVIDIA_MODEL')")
 .replaceAll('Buffer.byteLength(text)','new TextEncoder().encode(text).byteLength')
const wrapper=`
// Explicit origins prevent other browser sites reading responses. This is NOT authentication.
const origins = new Set((Deno.env.get('CHAT_ALLOWED_ORIGINS') || 'https://aureatine.cc.cd,https://www.aureatine.cc.cd,https://jusnie.github.io').split(',').map(value => value.trim()).filter(Boolean))
export async function serveRequest(request) {
 const origin=request.headers.get('origin') || ''
 const cors={ 'Vary':'Origin', 'Access-Control-Allow-Methods':'GET, POST, OPTIONS', 'Access-Control-Allow-Headers':'content-type, authorization, apikey, x-client-info', ...(origins.has(origin)?{'Access-Control-Allow-Origin':origin}:{}) }
 const fail=(status,error)=>new Response(JSON.stringify({error}),{status,headers:{...cors,'Content-Type':'application/json','Cache-Control':'no-store'}})
 if(origin&&!origins.has(origin))return fail(403,'Please use the chat on the Aureatine website.')
 if(request.method==='OPTIONS')return new Response(null,{status:204,headers:cors})
 // Bound bytes while reading, not only after allocating the entire body.
 let text=''
 if(request.method==='POST'&&request.body){
  const reader=request.body.getReader(),decoder=new TextDecoder();let size=0
  try{while(true){const {done,value}=await reader.read();if(done)break;size+=value.byteLength;if(size>16000){await reader.cancel();return fail(413,'The message is too long.')}text+=decoder.decode(value,{stream:true})}text+=decoder.decode()}catch{return fail(400,'Could not read the request.')}
 }
 const headers=Object.fromEntries(request.headers.entries())
 // Same-origin validation in the shared core runs only after the allowlist above.
 headers.host=origin?new URL(origin).host:new URL(request.url).host
 delete headers['x-forwarded-host']
 const responseHeaders={...cors}
 let payload=''
 const response={statusCode:200,setHeader(name,value){responseHeaders[name]=value},end(value){payload=value}}
 try{await handler({method:request.method,headers,body:text},response)}catch{return fail(500,'Chat is unavailable. Please try again.')}
 return new Response(payload,{status:response.statusCode,headers:responseHeaders})
}
Deno.serve(serveRequest)
`
