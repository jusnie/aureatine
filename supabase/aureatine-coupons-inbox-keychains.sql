-- BEGIN MODULE: coupon-helpers
-- Monday 00:00 in Manila for the current week.
create or replace function public.coupon_week_start() returns timestamptz
language sql stable set search_path = '' as $$
  select date_trunc('week', timezone('Asia/Manila', now())) at time zone 'Asia/Manila'
$$;
-- Six letters from A-Z without I or O. Each candidate is checked against existing codes.
create or replace function public.generate_coupon_code() returns text
language plpgsql set search_path = '' as $$
declare alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ'; candidate text; i integer; tries integer := 0;
begin
  loop
    candidate := '';
    for i in 1..6 loop
      candidate := candidate || substr(alphabet, 1 + (get_byte(uuid_send(gen_random_uuid()), 0) % 24), 1);
    end loop;
    if not exists(select 1 from public.coupon_codes where code = candidate) then return candidate; end if;
    tries := tries + 1;
    if tries > 20 then raise exception 'Could not generate a unique coupon code'; end if;
  end loop;
end $$;
-- A staff member may verify a brand only with the matching staff role.
create or replace function public.is_coupon_staff(p_brand text) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.staff_members s where s.user_id = auth.uid() and s.role = p_brand)
$$;
-- END MODULE: coupon-helpers

-- BEGIN MODULE: coupon-functions
create or replace function public.redeem_coupon(p_offer_id text, p_request_id uuid, p_expected_points integer)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  uid uuid := auth.uid(); wallet_points integer; offer public.coupon_offers%rowtype; existing public.coupon_codes%rowtype;
  used_this_week integer; new_code text; new_id uuid; ws timestamptz := public.coupon_week_start(); brand_label text;
begin
  if uid is null then return jsonb_build_object('ok',false,'code','SIGN_IN'); end if;
  if p_request_id is null or p_offer_id is null then return jsonb_build_object('ok',false,'code','INVALID_REQUEST'); end if;
  -- Serialize operations for one wallet; the browser never supplies a user ID or balance.
  select points into wallet_points from public.wallets where user_id = uid for update;
  if not found then return jsonb_build_object('ok',false,'code','WALLET_UNAVAILABLE'); end if;
  select * into existing from public.coupon_codes where request_id = p_request_id;
  if found then
    if existing.user_id <> uid or existing.offer_id <> p_offer_id then
      return jsonb_build_object('ok',false,'code','REQUEST_CONFLICT');
    end if;
    -- Retried request: return the same code without deducting Aurels again.
    return jsonb_build_object('ok',true,'code','REDEEMED','replayed',true,'coupon_code',existing.code,
      'offer_id',existing.offer_id,'status',existing.status,'balance',wallet_points,'points_spent',existing.points_spent);
  end if;
  select * into offer from public.coupon_offers where id = p_offer_id and published;
  if not found then return jsonb_build_object('ok',false,'code','UNAVAILABLE'); end if;
  if p_expected_points is distinct from offer.points_cost then
    return jsonb_build_object('ok',false,'code','PRICE_CHANGED');
  end if;
  select count(*) into used_this_week from public.coupon_codes
    where user_id = uid and offer_id = offer.id and created_at >= ws;
  if used_this_week >= offer.weekly_limit then
    return jsonb_build_object('ok',false,'code','WEEKLY_LIMIT','resets_at',ws + interval '7 days');
  end if;
  if wallet_points < offer.points_cost then
    return jsonb_build_object('ok',false,'code','NOT_ENOUGH_POINTS','balance',wallet_points);
  end if;
  new_code := public.generate_coupon_code();
  update public.wallets set points = points - offer.points_cost, updated_at = now() where user_id = uid;
  insert into public.coupon_codes(code,request_id,user_id,offer_id,points_spent)
    values(new_code,p_request_id,uid,offer.id,offer.points_cost) returning id into new_id;
  brand_label := case when offer.brand = 'apex' then 'APEX' else 'Aureatine' end;
  insert into public.member_notifications(user_id,kind,title,body)
    values(uid,'coupon',offer.title||' is ready',
      'Your code is '||new_code||'. Show it to '||brand_label||' staff to approve it. Each code works once.');
  return jsonb_build_object('ok',true,'code','REDEEMED','coupon_code',new_code,'redemption_id',new_id,
    'offer_id',offer.id,'status','active','balance',wallet_points-offer.points_cost,'points_spent',offer.points_cost);
end $$;

-- Own codes plus this week's usage per coupon.
create or replace function public.get_my_coupons() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare uid uuid := auth.uid(); ws timestamptz := public.coupon_week_start();
begin
  if uid is null then return jsonb_build_object('ok',false,'code','SIGN_IN'); end if;
  return jsonb_build_object(
    'ok', true,
    'resets_at', ws + interval '7 days',
    'weekly', coalesce((
      select jsonb_agg(jsonb_build_object('offer_id',o.id,'limit',o.weekly_limit,
        'used',(select count(*) from public.coupon_codes c where c.user_id = uid and c.offer_id = o.id and c.created_at >= ws)))
      from public.coupon_offers o where o.published), '[]'::jsonb),
    'codes', coalesce((
      select jsonb_agg(to_jsonb(x)) from (
        select c.code, c.offer_id, o.title, o.brand, c.status, c.created_at, c.used_at
        from public.coupon_codes c join public.coupon_offers o on o.id = c.offer_id
        where c.user_id = uid order by c.created_at desc limit 50
      ) x), '[]'::jsonb)
  );
end $$;

-- Staff check: an unknown code says INVALID_CODE. A known code outside the staff member's brand says STAFF_ONLY.
create or replace function public.staff_lookup_coupon(p_code text) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare norm text := upper(trim(coalesce(p_code,''))); c record;
begin
  if auth.uid() is null then return jsonb_build_object('ok',false,'code','SIGN_IN'); end if;
  if norm !~ '^[A-HJ-NP-Z]{6}$' then return jsonb_build_object('ok',false,'code','INVALID_CODE'); end if;
  select cc.code, cc.status, cc.created_at, cc.used_at, o.brand, o.title, p.display_name into c
    from public.coupon_codes cc
    join public.coupon_offers o on o.id = cc.offer_id
    left join public.member_profiles p on p.user_id = cc.user_id
    where cc.code = norm;
  if not found then return jsonb_build_object('ok',false,'code','INVALID_CODE'); end if;
  if not public.is_coupon_staff(c.brand) then return jsonb_build_object('ok',false,'code','STAFF_ONLY'); end if;
  return jsonb_build_object('ok',true,'code',c.code,'status',c.status,'brand',c.brand,'title',c.title,
    'member_name',c.display_name,'created_at',c.created_at,'used_at',c.used_at);
end $$;

-- Approves a coupon once. Repeats return ALREADY_USED and do not change the record.
create or replace function public.staff_use_coupon(p_code text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare norm text := upper(trim(coalesce(p_code,''))); c public.coupon_codes%rowtype; o public.coupon_offers%rowtype; ts timestamptz := now();
begin
  if auth.uid() is null then return jsonb_build_object('ok',false,'code','SIGN_IN'); end if;
  if norm !~ '^[A-HJ-NP-Z]{6}$' then return jsonb_build_object('ok',false,'code','INVALID_CODE'); end if;
  select * into c from public.coupon_codes where code = norm for update;
  if not found then return jsonb_build_object('ok',false,'code','INVALID_CODE'); end if;
  select * into o from public.coupon_offers where id = c.offer_id;
  if not public.is_coupon_staff(o.brand) then return jsonb_build_object('ok',false,'code','STAFF_ONLY'); end if;
  if c.status = 'used' then
    return jsonb_build_object('ok',false,'code','ALREADY_USED','used_at',c.used_at);
  end if;
  update public.coupon_codes set status = 'used', used_at = ts, used_by = auth.uid() where id = c.id;
  insert into public.member_notifications(user_id,kind,title,body)
    values(c.user_id,'coupon',o.title||' approved',
      'Staff approved your code '||c.code||'. Enjoy your coupon.');
  return jsonb_build_object('ok',true,'code','USED','coupon_code',c.code,'title',o.title,'used_at',ts);
end $$;

-- Member inbox: coupon updates and announcements, newest first, with an unread count.
create or replace function public.get_my_inbox() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare uid uuid := auth.uid();
begin
  if uid is null then return jsonb_build_object('ok',false,'code','SIGN_IN'); end if;
  return jsonb_build_object(
    'ok', true,
    'unread', (select count(*) from public.member_notifications n where n.user_id = uid and n.read_at is null)
            + (select count(*) from public.announcements a
               where not exists(select 1 from public.announcement_reads r where r.user_id = uid and r.announcement_id = a.id)),
    'items', coalesce((
      select jsonb_agg(to_jsonb(x)) from (
        select * from (
          select n.id::text as id, n.kind, n.title, n.body, n.created_at, (n.read_at is not null) as is_read
            from public.member_notifications n where n.user_id = uid
          union all
          select a.id::text, 'announcement', a.title, a.body, a.created_at,
            exists(select 1 from public.announcement_reads r where r.user_id = uid and r.announcement_id = a.id)
            from public.announcements a
        ) u order by u.created_at desc limit 50
      ) x), '[]'::jsonb)
  );
end $$;

create or replace function public.mark_inbox_read() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid();
begin
  if uid is null then return jsonb_build_object('ok',false,'code','SIGN_IN'); end if;
  update public.member_notifications set read_at = now() where user_id = uid and read_at is null;
  insert into public.announcement_reads(user_id,announcement_id)
    select uid, a.id from public.announcements a
    where not exists(select 1 from public.announcement_reads r where r.user_id = uid and r.announcement_id = a.id)
    on conflict do nothing;
  return jsonb_build_object('ok',true);
end $$;

-- Admins only. Publishes one announcement that every member sees in their inbox.
create or replace function public.admin_publish_announcement(p_title text, p_body text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); new_id uuid;
begin
  if uid is null or not exists(select 1 from public.app_admins where user_id = uid) then
    return jsonb_build_object('ok',false,'code','ADMIN_ONLY');
  end if;
  if char_length(trim(coalesce(p_title,''))) not between 1 and 120
     or char_length(trim(coalesce(p_body,''))) not between 1 and 2000 then
    return jsonb_build_object('ok',false,'code','INVALID_CONTENT');
  end if;
  insert into public.announcements(title,body,created_by) values(trim(p_title),trim(p_body),uid) returning id into new_id;
  return jsonb_build_object('ok',true,'announcement_id',new_id);
end $$;
