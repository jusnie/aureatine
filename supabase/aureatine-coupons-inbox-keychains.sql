-- AUREATINE: COUPONS, MEMBER INBOX, ANNOUNCEMENTS AND KEYCHAIN REWARD ITEMS
-- ONE FILE. Run this single file in the Supabase SQL Editor as the project owner.
-- Run it AFTER aureatine-full-setup.sql has been run once (it needs its tables).
-- Select all, then Run. Do not split it up. The whole install is one transaction:
-- if any part fails, everything in this run is rolled back.
-- Safe to re-run: existing rows and owner-changed costs are kept.
--
-- Coupons: 150 Aurels each. Each member can redeem each coupon up to 2 times per week.
-- The week runs Monday to Monday in Asia/Manila and resets automatically.
-- Each code is 6 letters (no I or O), is generated by the server, and works once.
-- Gym (APEX) coupons are approved by APEX staff. Shake (Aureatine) coupons are approved by Aureatine staff.
-- Inbox: coupon updates go to the member automatically. Admins publish announcements to all members.
-- No email is sent. No auth or SMTP settings are changed. Duplicate coupon requests are safe.
--
-- Apparel (Women's and Apparel): costs set as 600-800 Aurels (unknown or unbranded items) or 1000-1200 Aurels (known brands), by quality. Redeeming stays off.
-- Keychains: six color items, 160 Aurels each. Gear: Wrist Support Wraps 135, Compression Wrist Wraps 180 (3 designs), Weight Lifting Hook Grips 200, Clinkerman Weightlifting Grips 200. Redeeming stays OFF (redeem_enabled false)
-- until the owner turns it on. Each colour has its own redeemed-member count.
begin;

-- BEGIN MODULE: coupon-offers
create table if not exists public.coupon_offers (
  id text primary key check (id ~ '^[a-z0-9-]{3,60}$'),
  brand text not null check (brand in ('apex','aureatine')),
  title text not null check (char_length(title) between 1 and 120),
  points_cost integer not null check (points_cost > 0),
  weekly_limit integer not null default 2 check (weekly_limit between 1 and 20),
  published boolean not null default false
);
