-- BEGIN MODULE: coupon-codes
create table if not exists public.coupon_codes (
  id uuid primary key default gen_random_uuid(),
  code text not null unique check (code ~ '^[A-HJ-NP-Z]{6}$'),
  request_id uuid not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  offer_id text not null references public.coupon_offers(id),
  points_spent integer not null check (points_spent > 0),
  status text not null default 'active' check (status in ('active','used')),
  created_at timestamptz not null default now(),
  used_at timestamptz,
  used_by uuid references auth.users(id) on delete set null,
  constraint coupon_used_requires_time check (status <> 'used' or used_at is not null)
);
create index if not exists coupon_codes_weekly on public.coupon_codes(user_id, offer_id, created_at);
alter table public.coupon_codes enable row level security;
revoke all on public.coupon_codes from anon, authenticated;
grant all on public.coupon_codes to service_role;
-- END MODULE: coupon-codes

-- BEGIN MODULE: inbox-and-announcements
create table if not exists public.member_notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null default 'coupon' check (kind in ('coupon')),
  title text not null check (char_length(title) between 1 and 120),
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now(),
  read_at timestamptz
);
create index if not exists member_notifications_user on public.member_notifications(user_id, created_at desc);
